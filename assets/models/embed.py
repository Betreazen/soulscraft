"""Packs the build outputs into docs/showcase/js for the showcase page.

The page opens straight from disk, where a script cannot fetch a file, so models, data and
textures travel inside scripts (base64 and JSON). build.py runs this file; it also runs alone with
Blender's Python:  blender --background --factory-startup --python assets/models/embed.py

Writes (all generated, do not edit by hand):
    js/glb.js        SC.glb(id, base64) for every assets/models/*.glb
    js/data.js       SC.data(data/mobs.json), SC.altarData(data/altar.json), SC.trophyData
                     (data/trophies.json), SC.bookData(data/book.json)
    js/rigs.js       SC.rig(id, {sockets, texture, states: {part: flag}, clips: {name: {ticks, loop,
                     markers}}}) from assets/rigs, and SC.trophy(id, <mob>.trophy.json as it is)
    js/items.js      SC.item(id, {model, texture, display}) and SC.equipment(id, texture); display
                     is the model's own block or, for a sprite, the one of its parent. Block items
                     (parent soulscraft:block/...) are left out: the showcase draws blocks from
                     the blocks_<set>.glb. SC.blockTexture(id, png) for every block texture,
                     SC.effectIcon('soulscraft:<effect>', png) for every mob effect icon.
(js/blocks.js, the block registry, is written by build_blocks.py.)
    js/mobs/list.js  the mob scripts in js/mobs/, loaded by the page in this order
"""
import base64
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True
if HERE not in sys.path:
    sys.path.insert(0, HERE)

from items import PARENT_DISPLAY  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
JS = os.path.join(ROOT, 'docs', 'showcase', 'js')
NS = os.path.join(ROOT, 'assets', 'soulscraft')
HEAD = ["'use strict';", '// Generated by assets/models/embed.py. Do not edit by hand.']


def write(name, lines):
    path = os.path.join(JS, name)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(HEAD + lines) + '\n')
    return os.path.normpath(path)


def b64(path):
    with open(path, 'rb') as f:
        return base64.b64encode(f.read()).decode('ascii')


def js(obj):
    return json.dumps(obj, ensure_ascii=False, separators=(',', ':'), sort_keys=False)


def name_of(path, ext):
    return os.path.basename(path)[:-len(ext)]


def main():
    glbs = sorted(glob.glob(os.path.join(HERE, '*.glb')))
    write('glb.js', ["SC.glb('%s', '%s');" % (name_of(p, '.glb'), b64(p)) for p in glbs])

    with open(os.path.join(ROOT, 'data', 'mobs.json'), encoding='utf-8') as f:
        lines = ['SC.data(%s);' % js(json.load(f))]
    for name, call in (('altar', 'altarData'), ('trophies', 'trophyData'), ('book', 'bookData')):
        path = os.path.join(ROOT, 'data', name + '.json')
        if os.path.exists(path):
            with open(path, encoding='utf-8') as f:
                lines.append('SC.%s(%s);' % (call, js(json.load(f))))
    write('data.js', lines)

    rigs = []
    for p in sorted(glob.glob(os.path.join(ROOT, 'assets', 'rigs', '*.rig.json'))):
        with open(p, encoding='utf-8') as f:
            r = json.load(f)
        clips = {n: {'ticks': c['ticks'], 'loop': c['loop'], 'markers': c['markers']} for n, c in r['clips'].items()}
        states = {p['name']: p['state'] for p in r['parts'] if 'state' in p}
        rigs.append('SC.rig(%s, %s);' % (js(r['id']), js({'sockets': r['sockets'], 'texture': r['texture'], 'states': states, 'clips': clips})))
    for p in sorted(glob.glob(os.path.join(ROOT, 'assets', 'rigs', '*.trophy.json'))):
        with open(p, encoding='utf-8') as f:
            t = json.load(f)
        rigs.append('SC.trophy(%s, %s);' % (js(t['id']), js(t)))
    write('rigs.js', rigs)

    lines = []
    for p in sorted(glob.glob(os.path.join(NS, 'models', 'item', '*.json'))):
        item_id = name_of(p, '.json')
        with open(p, encoding='utf-8') as f:
            model = json.load(f)
        if model.get('parent', '').startswith('soulscraft:block/'):
            continue  # a block item: the block itself is in blocks_<set>.glb
        # A sprite names its texture as layer0, a model of elements as 0 (a wall head's item shows
        # its head item's model and texture).
        textures = model.get('textures', {})
        layer = textures.get('layer0') or textures.get('0') or 'soulscraft:item/' + item_id
        tex = os.path.join(NS, 'textures', 'item', layer.split('/', 1)[1] + '.png')
        display = model.get('display') or PARENT_DISPLAY[model['parent']]
        lines.append('SC.item(%s, %s);' % (js(item_id), js({'model': model, 'texture': 'data:image/png;base64,' + b64(tex), 'display': display})))
    for p in sorted(glob.glob(os.path.join(NS, 'textures', 'entity', 'equipment', '*', '*.png'))):
        lines.append('SC.equipment(%s, %s);' % (js(name_of(p, '.png')), js('data:image/png;base64,' + b64(p))))
    for p in sorted(glob.glob(os.path.join(NS, 'textures', 'block', '*.png'))):
        lines.append('SC.blockTexture(%s, %s);' % (js(name_of(p, '.png')), js('data:image/png;base64,' + b64(p))))
    for p in sorted(glob.glob(os.path.join(NS, 'textures', 'mob_effect', '*.png'))):
        lines.append('SC.effectIcon(%s, %s);' % (js('soulscraft:' + name_of(p, '.png')), js('data:image/png;base64,' + b64(p))))
    write('items.js', lines)

    scripts = sorted(name_of(p, '.js') for p in glob.glob(os.path.join(JS, 'mobs', '*.js')))
    scripts = [s for s in scripts if s != 'list']
    write(os.path.join('mobs', 'list.js'), ['SC.mobScripts(%s);' % js(scripts)])
    print('embed.py: %d models, %d rigs, %d items/armour, %d mob scripts' % (len(glbs), len(rigs), len(lines), len(scripts)))


if __name__ == '__main__':
    main()
