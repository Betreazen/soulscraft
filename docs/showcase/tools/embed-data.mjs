// Writes docs/showcase/js/data.js from data/*.json the way assets/models/embed.py does (same lines, same
// bytes), for a PC without Python and Blender: SC.data(mobs), SC.altarData, SC.trophyData, SC.bookData.
// Run from anywhere: node docs/showcase/tools/embed-data.mjs
// The rest of the generated scripts (glb.js, rigs.js, items.js) still come from the Blender build.
//
// embed.py is json.dumps(obj, ensure_ascii=False, separators=(',', ':')). Python keeps 1.0 a float and
// writes it "1.0"; JSON.stringify would write 1. So a number written with a dot or an exponent in the
// source is kept as a float here, and written the way Python's repr writes it.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const HEAD = ["'use strict';", '// Generated by assets/models/embed.py. Do not edit by hand.'];

class Float { constructor(v) { this.v = v; } }

const read = (name) =>
  JSON.parse(readFileSync(join(root, 'data', name + '.json'), 'utf8'), (_key, value, { source }) =>
    typeof value === 'number' && /[.eE]/.test(source) ? new Float(value) : value);

function pyFloat(v) {
  const a = Math.abs(v);
  if (!Number.isFinite(v) || (a !== 0 && (a < 1e-4 || a >= 1e16))) throw new Error('float ' + v + ' needs Python exponent form');
  return Number.isInteger(v) ? v.toFixed(1) : String(v);
}

function dump(x) {
  if (x instanceof Float) return pyFloat(x.v);
  if (Array.isArray(x)) return '[' + x.map(dump).join(',') + ']';
  if (x && typeof x === 'object') {
    // JS orders integer-like keys first; Python keeps the file's order. None are in the data.
    for (const k of Object.keys(x)) if (/^(0|[1-9]\d*)$/.test(k)) throw new Error('integer-like key ' + k);
    return '{' + Object.entries(x).map(([k, v]) => JSON.stringify(k) + ':' + dump(v)).join(',') + '}';
  }
  return JSON.stringify(x);
}

const lines = [`SC.data(${dump(read('mobs'))});`];
for (const [name, call] of [['altar', 'altarData'], ['trophies', 'trophyData'], ['book', 'bookData']]) {
  if (existsSync(join(root, 'data', name + '.json'))) lines.push(`SC.${call}(${dump(read(name))});`);
}
const out = join(root, 'docs', 'showcase', 'js', 'data.js');
writeFileSync(out, HEAD.concat(lines).join('\n') + '\n');
console.log('wrote', out, lines.length, 'blobs');
